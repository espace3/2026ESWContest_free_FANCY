# ── Pi Camera Module 3 (표준형, IMX708) 화각 ─────────────────────────────────
# 데이터시트 공칭 화각은 수평 66° / 수직 41° 이지만, 이는 센서 전체(16:9) 출력
# 기준이다. IMX708의 센서 모드는 전부 16:9라서 640x480 같은 4:3 출력은 가로를
# 잘라(crop) 쓰게 되고, 이때 유효 수평 화각은
#     2 * atan( (3/4) * tan(66°/2) ) ≈ 52°
# 로 줄어든다 (세로는 41° 유지). 그래서 4:3 캡처 기준값으로 52를 쓴다.
#   - 16:9 해상도(예: 1280x720)로 바꾸면 h를 66으로 되돌릴 것
#   - Camera Module 3 Wide(공칭 102°/67°)로 바꾸면 같은 방식으로 재계산할 것
#   - NoIR 표준형은 광학계가 표준형과 동일해서 이 값 그대로 유효
# 모터 위치 정확도 목표(<2°)에 직결되므로 최종적으로는 실측 검증 권장:
# 카메라 정면 거리 D(m)에서 옆으로 X(m) 이동했을 때 compute_pan_angle() 결과가
# atan(X/D)와 일치하는지 확인하면 된다.
_FOV_H_DEG = 52.0
_FOV_V_DEG = 41.0

