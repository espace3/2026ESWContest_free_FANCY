"""
target_fan / config.py
전체 프로젝트 설정을 한 곳에서 관리합니다.

2026-07 정리: 구세대 설계(Pi 4B + 서보모터 + MediaPipe + WebSocket 서버 + IR 리모컨 +
LLM 명령 해석) 항목을 전부 제거하고, 현행 설계(Pi 5 + 스테퍼 모터 + MoveNet MultiPose +
BLE)에서 실제로 쓰이거나 확정된 값만 남겼습니다. 과거 값이 필요하면 git 히스토리를
보세요. 스테퍼 핀 배정·릴레이 핀·BLE 설정은 배선/프로토콜이 확정될 때 추가합니다.
"""

import math

# 캡처 해상도 — 아래 fov/focal_px가 이 값 기준으로 유도되므로 여기서만 수정할 것
_CAM_W, _CAM_H = 640, 480

# ── Pi Camera Module 3 (표준형, IMX708) 화각 ─────────────────────────────────
# 데이터시트 공칭 화각은 수평 66° / 수직 41° 이지만, 이는 센서 전체(16:9) 출력
# 기준이다. IMX708의 센서 모드는 전부 16:9라서 640x480 같은 4:3 출력은 가로를
# 잘라(crop) 쓰게 되고, 이때 유효 수평 화각은
#     2 * atan( (3/4) * tan(66°/2) ) ≈ 52°
# 로 줄어든다 (세로는 41° 유지). 그래서 4:3 캡처 기준값으로 52를 쓴다.
#   - 16:9 해상도(예: 1280x720)로 바꾸면 h를 66으로 되돌릴 것
#   - Camera Module 3 Wide(공칭 102°/67°)로 바꾸면 같은 방식으로 재계산할 것
#   - NoIR 표준형은 광학계가 표준형과 동일해서 이 값 그대로 유효
# 모터 위치 정확도 목표(<2°)에 직결되므로 최종적으로는 실측 검증 권장:
# 카메라 정면 거리 D(m)에서 옆으로 X(m) 이동했을 때 compute_pan_angle() 결과가
# atan(X/D)와 일치하는지 확인하면 된다.
_FOV_H_DEG = 52.0
_FOV_V_DEG = 41.0

CFG: dict = {
    # ── 카메라 ──────────────────────────────────────────────────────────────
    "camera": {
        "width":  _CAM_W,
        "height": _CAM_H,
        # 카메라 프레임레이트는 곧 추론 FPS의 상한이다 — 구세대 값 20(Pi 4B CPU
        # 절약용)을 그대로 두면 추론이 20fps를 넘는지 확인할 수 없어 30으로 올림.
        "fps":    30,
    },

    # ── 카메라 FOV (화각, degree) ────────────────────────────────────────────
    "fov": {
        "h": _FOV_H_DEG,
        "v": _FOV_V_DEG,
    },

    # ── GPIO 핀 (BCM 번호) ──────────────────────────────────────────────────
    # TODO: 배선 확정 시 스테퍼 드라이버 핀(pan/tilt 각각 STEP/DIR/ENABLE)과
    # 릴레이 모듈 핀을 여기에 추가할 것 (hardware/motor_controller.py의 TODO 참고).
    # 실제 배선 전에 추측으로 채워 넣지 말 것.
    "pins": {},

    # ── 거리 추정 (어깨 너비 기반 — control/control_signal_generator.py) ─────
    "distance": {
        "ref_shoulder_cm": 40,   # 성인 평균 어깨 너비 (cm)
        # 초점거리(픽셀) — 수평 FOV에서 유도. 어깨 너비는 화면상 수평 거리라서
        # 수평 기준을 쓴다. 해상도/FOV를 바꾸면 자동으로 따라온다.
        "focal_px": (_CAM_W / 2) / math.tan(math.radians(_FOV_H_DEG / 2)),  # ≈ 656
        # estimate_distance_m(min_m=…, max_m=…)에 넘겨서 키포인트 잡음으로 인한
        # 비정상 추정값(초근거리/초원거리)을 잘라내는 용도
        "min_m": 0.3,
        "max_m": 5.0,
    },

    # ── 팬틸트 모터 회전 속도 거리 구간 (m) ──────────────────────────────────
    # 주의: 선풍기 풍량(약풍/중풍/강풍) 아님! 추정 거리로 팬틸트가 목표를 따라가는
    # "회전 속도" 단계를 고르는 용도다 (motor_speed_zone() 참고). 풍량은 사용자가
    # 앱에서 BLE로 부위별로 직접 지정하는 값이라 거리 추정과는 무관하다.
    "speed_zones": {
        "near": 1.0,   # ~1m
        "mid":  2.0,   # ~2m (초과하면 3단계)
    },
}
